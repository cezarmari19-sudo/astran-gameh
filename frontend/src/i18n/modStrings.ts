/** Mesaj pentru un cod de eroare al serverului (err.code); cade pe mesajul brut. */
export function modErr(lang: string, e: any): string {
  const code = e?.code as string | undefined;
  const dict = (lang === "ro" ? RO : EN) as S;
  if (code && dict["err_" + code]) return dict["err_" + code];
  return e?.message || "Error";
}
