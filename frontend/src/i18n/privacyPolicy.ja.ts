Astranは、ユーザーが未成年者である場合、追加の措置を適用します。

これには以下が含まれる場合があります:

- 年齢の確認;
- 保護者のメールアドレスの要求;
- 保護者の同意の取得;
- 特定の機能の制限;
- 特定の種類の広告の制限;
- 特定の種類のデータ譲渡の制限;
- 追加の安全対策。

子どもであるユーザーについては、データの販売や開示の特定の形態について、別途保護者の同意が必要となる場合、または法律によって制限される場合があります。

未成年者に適用される規則は、ユーザーが所在する国によって異なる場合があります。


